## Greatest Common Divisor

Let $D$ be a UFD, and $a_1, a_2, \ldots, a_n \in D$. Then $d \in D$ is called a **greatest common divisor** ($\gcd$) of $a_1, a_2, \ldots, a_n$ if

1. $d \mid a_i$ for $i \in \{1, 2, \ldots, n\}$, and
2. whenever $c \in D$ such that $c \mid a_i$ for $i \in \{1, 2, \ldots, n\}$, then $c \mid d$.

### Remark

Let $D$ be a UFD.

1. The $\gcd$ of a set of elements of $D$ is not unique. In fact, if $d$ and $d'$ are $\gcd$s of the same elements of $D$, then $d$ and $d'$ are associates.
2. A $\gcd$ of a set of elements of $D$ always exists.

---

## Content of a Polynomial

### Definition

Let $D$ be a UFD, and $f(x) = a_0 + a_1 x + \cdots + a_n x^n$ be a non-zero polynomial in $D[x]$.

1. The **content** of $f(x)$ is a $\gcd$ of $a_0, a_1, \ldots, a_n$.
2. Then $f(x)$ is said to be **primitive** if the content of $f(x)$ is a unit.

### Remark

Let $D$ be a UFD and $0 \neq f(x) \in D[x]$.

1. The content of $f(x)$ is unique up to associates.
2. If the content of $f(x)$ is $1$, then $f(x)$ is primitive.
3. Then $f(x)$ can be written as $f(x) = c \cdot g(x)$, where $c$ is the content of $f(x)$, and $g(x) \in D[x]$ with $g(x)$ primitive.
4. If $f(x) = d \cdot g(x)$, where $g(x)$ is a primitive polynomial in $D[x]$, then the content of $f(x)$ and $d$ are associates.
5. If $\deg f(x) > 0$ and $f(x)$ is an irreducible of $D[x]$, then $f(x)$ is primitive.

---

## Gauss' Lemma

### Lemma 1.22: Gauss' Lemma

If $D$ is a UFD, then the product of two primitive polynomials in $D[x]$ is again primitive.

### Remark

Let $D$ be a UFD. Then a finite product of primitive polynomials in $D[x]$ is still primitive.

---

## Irreducibles of $D[x]$

### Recall

The field of quotients $F$ of an integral domain $D$ is
$$F = \{a/b \mid a, b \in D, b \neq 0\},$$
and
$$D \cong \{a/1 \mid a \in D\} \subseteq F.$$

### Lemma 1.23

Let $D$ be a UFD, and $F$ be the field of quotients of $D$. If $f(x)$ is a non-constant polynomial in $D[x]$, then $f(x)$ is irreducible over $F$ whenever $f(x)$ is an irreducible of $D[x]$.

### Remark

1. Theorem 1.8 now follows from Lemma 1.23 and its proof.
2. Let $D$ be a UFD, and $F$ its field of quotients. If a non-constant $f(x) \in D[x]$ is primitive and is irreducible over $F$, then $f(x)$ is an irreducible of $D[x]$.
3. If $D$ is a UFD, then the irreducibles of $D[x]$ are the irreducibles of $D$, together with the non-constant primitive polynomials that are irreducible over $F$, where $F$ is the field of quotients of $D$.

---

## $D$ UFD $\Rightarrow$ $D[x]$ UFD

### Theorem 1.24

If $D$ is a UFD, then $D[x]$ is a UFD.

