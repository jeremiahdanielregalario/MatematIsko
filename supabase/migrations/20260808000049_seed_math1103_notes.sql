## Multiplicative Norms

### Definition

Let $D$ be an integral domain. A **multiplicative norm** on $D$ is a function $N : D \to \mathbb{Z}$ that satisfies the following:

1. $N(\alpha) = 0$ if and only if $\alpha = 0$
2. For all $\alpha, \beta \in D$, $N(\alpha\beta) = N(\alpha)N(\beta)$.

### Theorem 1.27

Let $D$ be an integral domain, and $N$ a multiplicative norm on $D$.

1. Then $N(1) = 1$.
2. If $u \in D$ is a unit, then $|N(u)| = 1$.
3. Suppose every $\alpha \in D$ such that $|N(\alpha)| = 1$ is a unit. Then $\pi$ is an irreducible of $D$ whenever $|N(\pi)| = p$, where $p$ is a prime in $\mathbb{Z}$.

