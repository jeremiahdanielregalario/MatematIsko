# 3. Unique Factorization Domains

---

## Factorization in Commutative Rings with Unity

### Recall

The rings $\mathbb{Z}$ and $F[x]$ (where $F$ is a field) are integral domains having several common properties.

**Extra Reading:** Effinger, Hicks, and Mullen, *Integers and Polynomials: Comparing the Close Cousins $\mathbb{Z}$ and $\mathbb{F}_q[x]$*

### Definition

Let $R$ be a commutative ring with unity, and $a, b \in R$. Then $a$ is said to **divide** $b$ (or $a$ is a factor of $b$, or $a$ is a divisor of $b$), denoted $a \mid b$, if there exists $c \in R$ such that $b = ac$.

### Remark

We write $a \nmid b$ whenever $a$ does not divide $b$.

### Remark

Let $a, b, c$ be elements of a commutative ring $R$ with unity $1$.

1. Then $a \mid a$, $1 \mid a$, and $a \mid 0$.
2. Then $a$ is a unit if and only if $a \mid 1$.
3. If $a \mid b$ and $b \mid c$, then $a \mid c$.
4. Then $a \mid b$ if and only if $\langle b \rangle \subseteq \langle a \rangle$.

---

## Associates

### Definition

Let $R$ be a commutative ring with unity, and $a, b \in R$. Then $b$ is said to be an **associate** of $a$ if $b = au$ for some unit $u \in R$.

### Remark

1. Let $R$ be a commutative ring with unity. Then the relation $a \sim b$ on $R$ where $b$ is an associate of $a$ defines an equivalence relation on $R$.
2. Let $D$ be an integral domain, and $a, b \in D$. Then the following are equivalent:
   - (i) $a$ and $b$ are associates
   - (ii) $a \mid b$ and $b \mid a$
   - (iii) $\langle a \rangle = \langle b \rangle$

---

## Irreducibles and Primes

### Definition

Let $D$ be an integral domain, and $0 \neq p \in D$ that is not a unit.

1. Then $p$ is an **irreducible** of $D$ if, whenever $a, b \in D$ such that $p = ab$, then either $a$ is a unit or $b$ is a unit.
2. Then $p$ is a **prime** of $D$ if, whenever $a, b \in D$ such that $p \mid ab$, then $p \mid a$ or $p \mid b$.

### Remark

Let $D$ be an integral domain, and $p \in D$.

1. If $p$ is an irreducible, then any associate of $p$ is also irreducible.
2. Then $p$ is a prime if and only if $\langle p \rangle$ is a non-zero prime ideal of $D$.

### Theorem 1.17

Let $D$ be an integral domain. Then every prime of $D$ is an irreducible of $D$.

---

## Principal Ideal Domains

### Definition

An integral domain $D$ is a **principal ideal domain** (PID) if every ideal of $D$ is a principal ideal.

### Theorem 1.18

Let $D$ be a PID. Then $p$ is an irreducible of $D$ if and only if $p$ is a prime of $D$.

---

## Unique Factorization Domains

### Definition

An integral domain $D$ is a **unique factorization domain** (UFD) if the following hold:

1. Every non-zero non-unit element of $D$ can be written as a product of a finite number of irreducibles of $D$.
2. The factorization of a non-zero non-unit element of $D$ into irreducibles of $D$ is unique up to associates and the order in which the factors appear.

### Remark

Condition 2 means that if $p_1 p_2 \cdots p_r$ and $q_1 q_2 \cdots q_s$ are two factorizations of some element of $D$ into irreducibles of $D$, then $r = s$ and for all $i \in \{1, 2, \ldots, s\}$, $q_i$ is an associate of some $p_j$, where $1 \leq j \leq r$.

**Extra Reading:** *New Number Systems Seek Their Lost Primes* by Kevin Hartnett

### Remark

If $D$ is a UFD, then $p$ is an irreducible of $D$ if and only if $p$ is a prime of $D$.

### Lemma 1.19

Let $R$ be a commutative ring. If $I_1 \subseteq I_2 \subseteq \cdots$ is an ascending chain of ideals $I_i$ in $R$, then $I = \bigcup_i I_i$ is an ideal of $R$.

---

## Ascending Chain of Ideals

### Lemma 1.20: Ascending Chain Condition for a PID

Let $D$ be a PID. If $I_1 \subseteq I_2 \subseteq \cdots$ is an ascending chain of ideals $I_i$ in $D$, then there exists a positive integer $r$ such that $I_s = I_r$ for $s \geq r$.

### Remark

1. Lemma 1.20 is equivalent to: In a PID, every strictly ascending chain of ideals $I_1 \subset I_2 \subset \cdots$ is of finite length.
2. We say that in a PID, the **ascending chain condition** (ACC) holds.

---

## PID $\Rightarrow$ UFD

### Theorem 1.21

Every PID is a UFD.

**Question:** UFD $\Rightarrow^{?}$ PID

**Answer:** No!

