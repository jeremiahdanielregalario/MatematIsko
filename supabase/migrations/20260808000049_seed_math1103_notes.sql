# 4. Euclidean Domains

---

### Definition

An integral domain $D$ is said to be a **Euclidean domain** (ED) if there is a function
$$v : D \setminus \{0\} \to \mathbb{N}_0 := \mathbb{N} \cup \{0\}$$
(called **Euclidean norm** / Euclidean valuation / measure on $D$) that satisfies the following:

1. For all $a, b \in D \setminus \{0\}$, $v(ab) \geq v(a)$.
2. For all $a, b \in D$, with $b \neq 0$, there exist $q, r \in D$ such that
$$a = bq + r,$$
where either $r = 0$ or $v(r) < v(b)$.

### Remark

The elements $q$ and $r$ in condition 2 are not unique.

---

## ED $\Rightarrow$ PID

### Recall

$\mathbb{Z}$ and $F[x]$ ($F$ a field) are PIDs.

### Theorem 1.25

Every ED is a PID.

### Remark

1. Every ED is a UFD.
2. Not every PID is an ED. e.g.: $\mathbb{Z}[\sqrt{-19}] = \{a + b(1 + \sqrt{-19})/2 \mid a, b \in \mathbb{Z}\}$ is a PID but not an ED (T. Motzkin, 1949).

**Extra Reading:** Campoli, *A principal ideal domain that is not a Euclidean domain*

---

## Integral Domains

The hierarchy of integral domains:

$$\text{ED} \Rightarrow \text{PID} \Rightarrow \text{UFD}$$

---

## $v(1)$

### Theorem 1.26

Let $D$ be an ED with Euclidean norm $v$.

1. Then $v(1)$ is minimal among all $v(a)$, where $a \in D \setminus \{0\}$.
2. Then $u \in D \setminus \{0\}$ is a unit if and only if $v(u) = v(1)$.

