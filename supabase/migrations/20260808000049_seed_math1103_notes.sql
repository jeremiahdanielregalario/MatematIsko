## Division Algorithm for $F[x]$

### Recall: Division Algorithm for $\mathbb{Z}$

Let $m, n \in \mathbb{Z}$ with $n > 0$. Then there exist unique integers $q$ and $r$ with the property

$$m = nq + r,$$

where $0 \leq r < n$.

### Theorem 1.3: Division Algorithm for $F[x]$

Let $F$ be a field, and $f(x), g(x) \in F[x]$ with $g(x) \neq 0$.

Then there exist unique polynomials $q(x), r(x) \in F[x]$ with the property that

$$f(x) = q(x)g(x) + r(x)$$

where $r(x) = 0$ or $\deg r(x) < \deg g(x)$.

### Remark

We call the unique polynomials $q(x)$ and $r(x)$ in Theorem 1.3 the **quotient** and **remainder**, respectively, upon dividing $f(x)$ by $g(x)$.

---

## Polynomial Factors

### Definition

Let $F$ be a field and $f(x) = a_0 + a_1 x + \cdots + a_n x^n \in F[x]$.

1. Then $g(x) \in F[x]$ is said to **divide** $f(x)$ or is a **factor** of $f(x)$ if there exists $q(x) \in F[x]$ such that $f(x) = q(x)g(x)$.
2. If $\alpha \in F$, then $f(\alpha) := a_0 + a_1 \alpha + \cdots + a_n \alpha^n$.
3. Here, we need the ring $R$ to be commutative so that if $f(x), g(x) \in F[x]$ and $h(x) := f(x)g(x)$, then $h(\alpha) = f(\alpha)g(\alpha)$.

---

## Consequences of the Division Algorithm for $F[x]$

### Corollary 1.4: Remainder Theorem

Let $F$ be a field, and $a \in F$. Then the remainder when $f(x) \in F[x]$ is divided by $x - a$ is $f(a)$.

### Corollary 1.5: Factor Theorem

Let $F$ be a field, $a \in F$, and $f(x) \in F[x]$. Then $x - a$ is a factor of $f(x)$ if and only if $f(a) = 0$.

### Corollary 1.6

A polynomial $f(x) \in F[x]$ of positive degree $n$ has at most $n$ distinct zeros in the field $F$.

### Remark

1. Lagrange first proved Corollary 1.6 for $F = \mathbb{Z}_p$.
2. Corollary 1.6 is not true for arbitrary polynomial rings.

