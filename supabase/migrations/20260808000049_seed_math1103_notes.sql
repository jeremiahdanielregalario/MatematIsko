## Homomorphisms

### Recall

Let $R$ and $R'$ be rings.

1. A **ring homomorphism** from $R$ to $R'$ is a mapping $\varphi : R \to R'$ such that for any $a, b \in R$,
$$\varphi(a + b) = \varphi(a) + \varphi(b),$$
$$\varphi(ab) = \varphi(a)\varphi(b).$$

2. An **isomorphism** from $R$ to $R'$ is a bijective homomorphism from $R$ to $R'$. The rings $R$ and $R'$ are **isomorphic**, written $R \cong R'$, if there is an isomorphism from $R$ to $R'$.

### Evaluation Homomorphism

### Remark

Let $F$ be a subfield of a field $E$, and $\alpha \in E$. Then $\varphi_\alpha : F[x] \to E$ given by
$$\varphi_\alpha(a_0 + a_1 x + \cdots + a_n x^n) = a_0 + a_1 \alpha + \cdots + a_n \alpha^n$$
is a homomorphism of $F[x]$ into $E$ called the **evaluation homomorphism** at $\alpha$.

The homomorphism $\varphi_\alpha$ satisfies the following properties:

1. $\varphi_\alpha(x) = \alpha$
2. If $a \in F$ then $\varphi_\alpha(a) = a$.

### Recall

Let $\varphi : R \to R'$ be a ring homomorphism.

1. The **kernel** of $\varphi$ is
$$\ker \varphi = \{a \in R \mid \varphi(a) = 0'\},$$
where $0'$ is the additive identity of $R'$.
2. The kernel of $\varphi$ is an ideal of $R$.
3. **First Isomorphism Theorem for Rings:** The map $\mu : R / \ker \varphi \to \varphi(R)$, given by $a + \ker \varphi \mapsto \varphi(a)$ is a ring isomorphism and so
$$R / (\ker \varphi) \cong \varphi(R).$$

