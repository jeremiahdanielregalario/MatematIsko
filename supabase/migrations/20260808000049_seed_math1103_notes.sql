# 2. Review of Ideals, Factor Rings, and Homomorphisms

---

## Ideals

### Recall

1. An **ideal** $I$ of a ring $R$ is a subring of $R$ such that for every $r \in R$ and for every $a \in I$, $ra \in I$ and $ar \in I$.
2. **Ideal Test:** Let $R$ be a ring. Then $\emptyset \neq I \subseteq R$ is an ideal of $R$ if and only if:
   - (a) for all $a, b \in I$, $a - b \in I$, and
   - (b) for all $r \in R$ and for all $a \in I$, $ra \in I$ and $ar \in I$.
3. If $R$ is a ring with unity, and $I$ is an ideal of $R$ containing a unit, then $I = R$.
4. The ideals of a field $F$ are $\{0\}$ and $F$.

---

## Principal Ideals

### Definition

Let $R$ be a commutative ring with unity.

1. If $a \in R$ then the ideal $\langle a \rangle := \{ra \mid r \in R\}$ is called the **principal ideal** generated by $a$.
2. An ideal $I$ of $R$ is said to be a **principal ideal** if $I = \langle a \rangle$ for some $a \in R$.

---

## Ideals of $F[x]$

### Theorem 1.13

Let $F$ be a field. Then every ideal of $F[x]$ is a principal ideal.

### Remark

Let $F$ be a field.

1. Suppose $\{0\} \neq I$ is an ideal of $F[x]$ and $g(x) \in F[x]$. Then $I = \langle g(x) \rangle$ if and only if $g(x)$ is a non-zero polynomial of minimum degree in $I$.
2. If $f(x), g(x) \in F[x]$, then $f(x)$ divides $g(x)$ if and only if $\langle f(x) \rangle \supseteq \langle g(x) \rangle$.

---

## Factor Rings

### Recall

Let $I$ be an ideal of a ring $R$.

1. The **factor ring** (or quotient ring) of $R$ modulo $I$ is the set $R/I = \{a + I \mid a \in R\}$ together with the binary operations
$$(a + I) + (b + I) = (a + b) + I,$$
$$(a + I)(b + I) = ab + I.$$

   Its additive identity is $0 + I = I$, and if $a + I \in R/I$ then $-(a + I) = -a + I$.

2. If $R$ is commutative, then $R/I$ is commutative.
3. If $R$ has unity $1$, then $R/I$ has unity $1 + I$. In addition, if $a$ is a unit of $R$, then $a + I$ is a unit of $R/I$ with
$$(a + I)^{-1} = a^{-1} + I.$$

---

## Maximal and Prime Ideals

### Recall

Let $R$ be a ring.

1. An ideal $M \neq R$ is a **maximal ideal** of $R$ if whenever $I$ is an ideal of $R$ such that $M \subseteq I \subseteq R$, then $I = M$ or $I = R$.
2. If $R$ is commutative, then an ideal $P \neq R$ is a **prime ideal** of $R$ if whenever $a, b \in R$ such that $ab \in P$, then $a \in P$ or $b \in P$.

### Recall

Let $R$ be a commutative ring with unity $1 \neq 0$, and $I$ an ideal of $R$.

1. Then $R/I$ is a **field** if and only if $I$ is a **maximal ideal** of $R$.
2. Then $R/I$ is an **integral domain** if and only if $I$ is a **prime ideal** of $R$.
3. If $I$ is a maximal ideal of $R$, then $I$ is a prime ideal of $R$.

---

## Maximal Ideals of $F[x]$

### Theorem 1.14

Let $F$ be a field and $p(x) \in F[x]$. Then $\langle p(x) \rangle$ is a maximal ideal of $F[x]$ if and only if $p(x)$ is irreducible over $F$.

### Remark

If $F$ is a field, and $p(x)$ is an irreducible polynomial in $F[x]$, then $F[x] / \langle p(x) \rangle$ is a field.

---

## Primes in $F[x]$

### Corollary 1.5

Let $F$ be a field and $p(x), r(x), s(x) \in F[x]$.

If $p(x)$ is irreducible over $F$ and $p(x)$ divides $r(x)s(x)$, then $p(x)$ divides $r(x)$ or $p(x)$ divides $s(x)$.

### Remark

In general, suppose $F$ is a field and $p(x), r_1(x), r_2(x), \ldots, r_n(x) \in F[x]$.

If $p(x)$ is irreducible over $F$ and $p(x)$ divides $r_1(x) r_2(x) \cdots r_n(x)$, then $p(x)$ divides $r_i(x)$ for at least one $i$, $1 \leq i \leq n$.

---

## Unique Factorization in $F[x]$

### Theorem 1.6

Let $F$ be a field. Then every non-constant polynomial $f(x) \in F[x]$ can be factored in $F[x]$ into a product of irreducible polynomials over $F$, the irreducible polynomials being unique except for order and for unit factors in $F$.

